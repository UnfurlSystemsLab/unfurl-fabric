package com.unfurl.fabric.studio;

import com.unfurl.fabric.runtime.RuntimeBindingInputs;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Clock;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;
import java.util.function.Supplier;
import java.util.regex.Pattern;

/**
 * Repository: a tenant's deployment environments (LLD-fabric-studio-api, <i>Deployment Environments</i>), kept in the
 * tenant-keyed map Studio persists with the rest of its state.
 *
 * <p>Responsibilities: revision-checked create, replace and delete; and the save-time check, which lists every problem
 * with its field path. The check reuses the code that reads the same inputs elsewhere: a target is built as a
 * {@code DeploymentTarget}, its kind is one the server's {@code EmitterBootstrap} installs, and the binding inputs are read
 * by {@link RuntimeBindingInputs#fromMap}, one input at a time so every problem is named. Identity references must be
 * {@code secret://} or {@code config://} URIs. Rules that depend on a contract are the emit-plan preview's.
 *
 * <p>Thread safety: writes are serialized per instance; reads see a consistent snapshot of a tenant's map.
 */
public final class StudioDeploymentEnvironments {
    /** A save that breaks a rule; the problems name each field. */
    public static final String INVALID = "ENVIRONMENT_INVALID";
    /** A save or delete whose expected revision is not the stored one. */
    public static final String CONFLICT = "ENVIRONMENT_REVISION_CONFLICT";
    /** A name the tenant has no environment for. */
    public static final String UNKNOWN = "ENVIRONMENT_UNKNOWN";

    private static final Pattern NAME = Pattern.compile("[a-z0-9][a-z0-9-]{0,62}");

    /**
     * Target options the emit-plan preview produces itself from the compile record and Studio's configuration, so an
     * environment never names them (LLD-fabric-studio-api, Deployment Environments, Reserved options): the emitter would
     * otherwise read the operator's file while the preview reports what Studio generated.
     */
    static final java.util.Set<String> RESERVED_OPTIONS = java.util.Set.of(
            com.unfurl.fabric.deploy.EmitTargetInputs.CONTRACT,
            com.unfurl.fabric.deploy.EmitTargetInputs.PROFILE,
            com.unfurl.fabric.deploy.EmitTargetInputs.RUNTIME_BINDING,
            com.unfurl.fabric.deploy.EmitTargetInputs.DCP_RUNTIME_BUNDLE,
            com.unfurl.fabric.deploy.EmitTargetInputs.COMPONENT_ARTIFACTS,
            com.unfurl.fabric.deploy.EmitTargetInputs.TRUST_KEYS);

    /**
     * The reserved options a target names, each as a problem at {@code target.options.<key>}; shared by the save-time
     * check and the preview's own check of an environment stored before the rule.
     */
    static List<Problem> reservedOptionProblems(StudioDeploymentEnvironment.Target target) {
        return target.options().keySet().stream().filter(RESERVED_OPTIONS::contains).sorted()
                .map(key -> new Problem("target.options." + key, "is generated by the emit-plan preview from the compile"
                        + " record and Studio's configuration; an environment does not name it"))
                .toList();
    }

    private final Map<String, Map<String, StudioDeploymentEnvironment>> byTenant;
    private final Runnable persist;
    private final Clock clock;
    private final Supplier<List<String>> installedKinds;

    /**
     * @param byTenant       the tenant-keyed map Studio persists; this repository owns writes to it.
     * @param persist        saves Studio state after a change.
     * @param clock          the time source of {@code updatedAt}.
     * @param installedKinds the target kinds the server's emitters provide.
     */
    StudioDeploymentEnvironments(Map<String, Map<String, StudioDeploymentEnvironment>> byTenant, Runnable persist,
                                 Clock clock, Supplier<List<String>> installedKinds) {
        this.byTenant = byTenant;
        this.persist = persist;
        this.clock = clock;
        this.installedKinds = installedKinds;
    }

    /** One problem of a refused save. @param path the field path. @param message what is wrong. */
    public record Problem(String path, String message) {
    }

    /** A refused save: {@value #INVALID}, with every problem. */
    public static final class Invalid extends IllegalArgumentException {
        private final List<Problem> problems;

        public Invalid(List<Problem> problems) {
            super(INVALID + ": " + String.join("; ", problems.stream().map(p -> p.path() + ": " + p.message()).toList()));
            this.problems = List.copyOf(problems);
        }

        /** @return every problem, with its field path. */
        public List<Problem> problems() {
            return problems;
        }
    }

    /** A save or delete against a revision that is not the stored one: {@value #CONFLICT}. */
    public static final class Conflict extends RuntimeException {
        private final long currentRevision;

        Conflict(String name, long expected, long current) {
            super(CONFLICT + ": environment " + name + " is at revision " + current + "; the request expected " + expected);
            this.currentRevision = current;
        }

        /** @return the stored revision, 0 when the environment does not exist. */
        public long currentRevision() {
            return currentRevision;
        }
    }

    /** A name the tenant has no environment for: {@value #UNKNOWN}. */
    public static final class Unknown extends RuntimeException {
        Unknown(String name) {
            super(UNKNOWN + ": the tenant has no deployment environment named " + name);
        }
    }

    /** The tenant's environments, by name. */
    List<StudioDeploymentEnvironment> list(String tenant) {
        return byTenant.getOrDefault(tenant, Map.of()).values().stream()
                .sorted(Comparator.comparing(StudioDeploymentEnvironment::name))
                .toList();
    }

    /** The tenant's environment with that name, if any. */
    Optional<StudioDeploymentEnvironment> find(String tenant, String name) {
        return Optional.ofNullable(byTenant.getOrDefault(tenant, Map.of()).get(name));
    }

    /**
     * Creates or replaces an environment.
     *
     * @param tenant  the tenant.
     * @param name    the environment's name.
     * @param request the expected revision and the new content.
     * @return the stored environment, at its new revision.
     * @throws Conflict when the expected revision is not the stored one (0 for an environment that exists).
     * @throws Invalid  listing every problem of the content.
     */
    synchronized StudioDeploymentEnvironment save(String tenant, String name, StudioDeploymentEnvironmentRequest request) {
        if (request == null) {
            throw new Invalid(List.of(new Problem("", "a request body with expectedRevision, target and bindings is required")));
        }
        StudioDeploymentEnvironment stored = find(tenant, name).orElse(null);
        long current = stored == null ? 0 : stored.revision();
        if (request.expectedRevision() != current) {
            throw new Conflict(name, request.expectedRevision(), current);
        }
        List<Problem> problems = problems(tenant, name, request.target(), request.bindings());
        if (!problems.isEmpty()) {
            throw new Invalid(problems);
        }
        StudioDeploymentEnvironment saved = new StudioDeploymentEnvironment(name, current + 1, clock.instant(),
                request.target(), request.bindings());
        Map<String, StudioDeploymentEnvironment> environments = new LinkedHashMap<>(byTenant.getOrDefault(tenant, Map.of()));
        environments.put(name, saved);
        commit(tenant, environments);
        return saved;
    }

    /**
     * Deletes an environment.
     *
     * @throws Unknown  when there is none with that name.
     * @throws Conflict when the expected revision is not the stored one.
     */
    synchronized void delete(String tenant, String name, long expectedRevision) {
        StudioDeploymentEnvironment stored = find(tenant, name).orElseThrow(() -> new Unknown(name));
        if (stored.revision() != expectedRevision) {
            throw new Conflict(name, expectedRevision, stored.revision());
        }
        Map<String, StudioDeploymentEnvironment> environments = new LinkedHashMap<>(byTenant.getOrDefault(tenant, Map.of()));
        environments.remove(name);
        commit(tenant, environments);
    }

    /**
     * Unit of work: makes the tenant's new environments current and writes Studio state; when the write fails, the
     * tenant's previous environments are restored before the failure is rethrown, so a failed save or delete changes
     * nothing (LLD-fabric-studio-api, <i>Deployment Environments</i>, Saving).
     */
    private void commit(String tenant, Map<String, StudioDeploymentEnvironment> environments) {
        Map<String, StudioDeploymentEnvironment> previous = byTenant.get(tenant);
        byTenant.put(tenant, new ConcurrentHashMap<>(environments));
        try {
            persist.run();
        } catch (RuntimeException failed) {
            if (previous == null) {
                byTenant.remove(tenant);
            } else {
                byTenant.put(tenant, previous);
            }
            throw failed;
        }
    }

    /**
     * The save-time check: every problem of a name, target and binding inputs, each with its field path.
     *
     * @return the problems; empty when the content may be stored.
     */
    List<Problem> problems(String tenant, String name, StudioDeploymentEnvironment.Target target,
                           StudioDeploymentEnvironment.Bindings bindings) {
        List<Problem> problems = new ArrayList<>();
        if (name == null || !NAME.matcher(name).matches()) {
            problems.add(new Problem("name", "'" + name + "' must match " + NAME.pattern()));
        }
        StudioDeploymentEnvironment.Target safeTarget = target == null ? StudioDeploymentEnvironment.Target.EMPTY : target;
        if (safeTarget.kind() == null) {
            problems.add(new Problem("target.kind", "a target kind is required; installed: " + installedKinds.get()));
        } else {
            if (!installedKinds.get().contains(safeTarget.kind())) {
                problems.add(new Problem("target.kind", "'" + safeTarget.kind() + "' is not an installed emitter; installed: "
                        + installedKinds.get()));
            }
            try {
                safeTarget.deploymentTarget();
            } catch (IllegalArgumentException | NullPointerException invalid) {
                problems.add(new Problem("target", invalid.getMessage()));
            }
        }
        problems.addAll(reservedOptionProblems(safeTarget));
        StudioDeploymentEnvironment.Bindings safeBindings = bindings == null ? StudioDeploymentEnvironment.Bindings.EMPTY : bindings;
        if (safeBindings.timeoutMs() != null && safeBindings.timeoutMs() <= 0) {
            problems.add(new Problem("bindings.timeoutMs", "must be a positive whole number of milliseconds"));
        }
        if (safeBindings.identity() != null) {
            safeBindings.identity().references().forEach((path, ref) -> {
                if (!ref.startsWith("secret://") && !ref.startsWith("config://")) {
                    problems.add(new Problem(path, "must be a secret:// or config:// reference, never a value"));
                }
            });
        }
        problems.addAll(bindingProblems(tenant, safeTarget.environment(), safeBindings));
        return problems;
    }

    /**
     * Reads each binding input the way the binding tools do, one input at a time, so a problem in one does not hide a
     * problem in another. The documentation visibility text is read from a temporary file that is deleted at once.
     */
    private static List<Problem> bindingProblems(String tenant, String environment, StudioDeploymentEnvironment.Bindings bindings) {
        Path visibility = null;
        try {
            if (bindings.documentation() != null && bindings.documentation().visibility() != null) {
                visibility = Files.createTempFile("studio-environment-visibility-", ".yaml");
                Files.writeString(visibility, bindings.documentation().visibility(), StandardCharsets.UTF_8);
            }
            Map<String, Object> all = bindings.toolArguments(tenant, environment, visibility);
            List<Problem> problems = new ArrayList<>();
            Map<String, String> paths = new LinkedHashMap<>();
            paths.put("serviceBaseUrls", "bindings.serviceBaseUrls");
            paths.put("disableBindings", "bindings.disabledBindings");
            paths.put("documentationVisibilityDefault", "bindings.documentation");
            for (Map.Entry<String, String> input : paths.entrySet()) {
                Map<String, Object> one = new LinkedHashMap<>();
                if (all.containsKey(input.getKey())) one.put(input.getKey(), all.get(input.getKey()));
                if ("documentationVisibilityDefault".equals(input.getKey())) {
                    for (String key : List.of("documentationVisibilityPath", "catalogObservationIntervalMs",
                            "catalogObservationMaxBackoffMs")) {
                        if (all.containsKey(key)) one.put(key, all.get(key));
                    }
                }
                try {
                    RuntimeBindingInputs.fromMap(one, Path::of);
                } catch (IllegalArgumentException invalid) {
                    problems.add(new Problem(input.getValue(), invalid.getMessage()));
                }
            }
            return problems;
        } catch (IOException unwritable) {
            throw new IllegalStateException("unable to check the documentation visibility: " + unwritable.getMessage(), unwritable);
        } finally {
            if (visibility != null) {
                try {
                    Files.deleteIfExists(visibility);
                } catch (IOException ignored) {
                    // A temporary file the system cleans; it holds no secret, only visibility settings.
                }
            }
        }
    }
}
